export function exposeLegacyGlobals({
  auth,
  apiKeys,
  userSettings,
  utils,
  theme,
  websocket,
  storage,
  sync,
  ui,
  lifecycle,
  rendering,
  navigation,
  todos,
  projects,
  sections,
  dragDrop,
  viewPreferences,
  toastUndo,
  push,
}) {
  Object.assign(window, {
    ...auth,
    ...apiKeys,
    ...userSettings,
    ...utils,
    ...theme,
    ...websocket,
    ...storage,
    ...sync,
    ...ui,
    ...lifecycle,
    ...rendering,
    ...navigation,
    ...todos,
    ...projects,
    ...sections,
    ...dragDrop,
    ...viewPreferences,
    ...toastUndo,
    ...push,
  });
}
