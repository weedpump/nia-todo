#!/usr/bin/env python3
"""Generate the offline JS unit registry from the backend's canonical resource."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "api/resources/quantity_units.json"
TARGET = ROOT / "web/static/js/core/quantity-unit-data.js"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in registry is stale")
    args = parser.parse_args()
    registry = json.loads(SOURCE.read_text(encoding="utf-8"))
    output = (
        "// Generated by scripts/generate_quantity_unit_data.py; do not edit.\n"
        "// Source: api/resources/quantity_units.json (Unicode CLDR, Unicode-3.0).\n"
        "export const quantityUnits = "
        + json.dumps(registry["units"], ensure_ascii=False, indent=2, sort_keys=True)
        + ";\n\nexport const quantityUnitDefinitions = "
        + json.dumps(registry["definitions"], ensure_ascii=False, indent=2, sort_keys=True)
        + ";\n\nexport const recipeQuantityPolicy = "
        + json.dumps(registry["recipe_rounding"], ensure_ascii=False, indent=2, sort_keys=True)
        + ";\n"
    )
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            parser.exit(1, "Quantity unit data is stale; run scripts/generate_quantity_unit_data.py\n")
    else:
        TARGET.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
